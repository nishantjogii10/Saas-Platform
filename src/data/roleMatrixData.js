// Helper to calculate modules count and list based on role and permissions
export const getAccessibleModulesForRole = (roleKey, matrix) => {
  const rolePerms = matrix[roleKey] || {};
  const accessible = [];
  MODULES_LIST.forEach((mod) => {
    const perm = rolePerms[mod.key] || 'no_access';
    if (perm !== 'no_access') {
      accessible.push({
        ...mod,
        permission: perm,
      });
    }
  });
  return accessible;
};

